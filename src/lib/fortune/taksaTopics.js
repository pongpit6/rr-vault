const topicAdvice = (planet, id) => id === 'health' ? HEALTH_ACTION[planet] : SUB_FOCUS[planet][id]

export function taksaMainTopics(main) {
  return topicRows(TOPICS.map(([id], index) => {
    const [theme] = PLANET_TOPICS[main][index]
    return [`เน้น${theme}`, topicAdvice(main, id)]
  }))
}

export function taksaTopics(main, sub, birthPlanet) {
  const tone = toneOf(main, sub)
  const bhumi = bhumiOf(birthPlanet).find(x => x.planet === sub)?.name
  return topicRows(TOPICS.map(([id], index) => {
    const [longTheme] = PLANET_TOPICS[main][index]
    const [shortTheme, helpful, careful, check] = PLANET_TOPICS[sub][index]
    const useCaution = tone === '!' || (tone === '±' && (id === 'money' || id === 'work'))
    const advice = useCaution ? check : topicAdvice(sub, id)
    const healthContext = id === 'health' && bhumi === 'อายุ' ? ' · ดาวแทรกอยู่ภูมิอายุของคุณ' : ''
    const reason = main === sub
      ? `${PLANET[main].name}ทั้งเสวยและแทรก เรื่อง${longTheme}จึงเด่นทั้งช่วงยาวและช่วงนี้${healthContext}`
      : `${PLANET[main].name}เสวยให้ดูเรื่อง${longTheme} ส่วน${PLANET[sub].name}แทรกให้ใส่ใจ${shortTheme}ในช่วงนี้${healthContext}`
    return [useCaution ? careful : helpful, advice, reason]
  }))
}
