function readingOf(event, N) {
  if (event.k === 'star') return STAR[event.symbol]
  if (event.k === 'vaultOpen' || event.k === 'vaultVisit') return event.role === 2 ? VAULT_MONEY : GROUP[event.role]
  if (event.k !== 'triad' && event.k !== 'season') return REACTIONS[event.k]
  if (N.unfav.includes(event.element)) return event.role === 2
    ? ['money', 'ระวังรับภาระเงินเกินที่วางไว้', 'เช็กยอดที่ต้องจ่ายเองและข้อผูกมัดก่อนตกลง', 'เผื่องบสำหรับภาระที่ยังไม่นิ่ง และทบทวนยอดจริงก่อนเพิ่มรายการประจำ']
    : ['work', 'ระวังรับงานเกินกำลัง', 'เช็กเวลาและสิ่งที่ต้องส่งก่อนตอบรับงานเพิ่ม', 'เทียบปริมาณงานกับกำลังทีมทุกครั้งก่อนขยายขอบเขต']
  return GROUP[event.role]
}

export function baziTopics(N, r, c, events, period) {
  const long = period === 'ปี' || period === 'เสาโชค'
  const stemIsTough = N.unfav.includes(stemEl(c % 10))
  const base = { work: WORK[r.god], money: MONEY[r.god], health: HEALTH[r.god] }
  const signals = events.map(event => ({ event, reading: readingOf(event, N) })).filter(x => x.reading)
  return topicRows(TOPICS.map(([id]) => {
    const matching = signals.filter(x => x.reading[0] === id)
    const leading = matching.find(x => x.event.tone === 'bad' || x.reading[1].startsWith('ระวัง')) ?? matching[0]
    if (leading) {
      const [, headline, short, plan] = leading.reading
      const other = matching.find(x => x !== leading && x.event.tone === 'good' && !x.reading[1].startsWith('ระวัง'))
      const mixed = other && (leading.event.tone === 'bad' || leading.reading[1].startsWith('ระวัง'))
      return [headline, (long ? plan ?? short : short) + (mixed ? ` อีกด้านหนึ่ง ${other.reading[1]}` : ''),
        `จาก${leading.event.title}${mixed ? ` ร่วมกับ${other.event.title}` : ''}`]
    }
    if (base[id]) {
      const [headline, short, plan] = base[id]
      const adjust = stemIsTough && headline.startsWith('ดีสำหรับ')
      const title = adjust ? 'ค่อย ๆ ' + headline.slice('ดีสำหรับ'.length) : headline
      return [title, long ? plan : short, `ก้าน${period}เป็น${GOD_TH[r.god]}${adjust ? ' โดยธาตุของก้านเป็นจุดที่ผังให้ระวัง' : ''}`]
    }
    return NO_SIGNAL[id]
  }))
}
